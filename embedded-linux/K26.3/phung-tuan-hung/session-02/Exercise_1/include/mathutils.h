#ifndef MATHUTILS_H
#define MATHUTILS_H

/* Add two integers */
int math_add(int a, int b);

/* Subtract two integers (a - b) */
int math_sub(int a, int b);

/* Compute the factorial of a non-negative integer.
 * Returns -1 if n is negative (invalid input). */
int math_factorial(int n);

#endif /* MATHUTILS_H */
