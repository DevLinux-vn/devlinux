static inline int ssd1306_font_supported(unsigned char ch)
{
	return (ch >= 'A' && ch <= 'Z') || (ch >= 'a' && ch <= 'z') ||
	       (ch >= '0' && ch <= '9') || ch == ' ' || ch == '-' ||
	       ch == '.' || ch == '!' || ch == '?';
}
